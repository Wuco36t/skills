import { checkSafety } from '../domain/safety'

type Unit = Ingredient['unit']

const ing = (aisle: Aisle) => (name: string, quantity: number, unit: Unit = 'g'): Ingredient => ({
  name,
  quantity,
  unit,
  aisle,
})
const P = ing('produce') // fruit and vegetables
const D = ing('dairy-eggs')
const F = ing('fish')
const B = ing('bakery')
const S = ing('pantry')
const Z = ing('frozen')

const B_ = 'breakfast'
const L = 'lunch'
const N = 'dinner'
const K = 'snack'

function r(
  id: string,
  sl: string,
  en: string,
  slots: Slot[],
  minutes: number,
  nutrients: Nutrient[],
  ingredients: Ingredient[],
  steps: string[],
): Recipe {
  return {
    id,
    title: { sl, en },
    slots,
    minutes,
    nutrients,
    ingredients,
    steps,
    safety: checkSafety(en, ingredients),
  }
}

